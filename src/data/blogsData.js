export function getAllBlogs() {
    return blogsData;
}

export function getBlogBySlug(slug) {
    return blogsData.find((blog) => blog.slug === slug);
}

export function getFeaturedBlog() {
    return blogsData.find((blog) => blog.featured) || blogsData[0];
}

export function getRelatedBlogs(currentSlug, category, limit = 3) {
    const filtered = blogsData.filter(
        (blog) => blog.slug !== currentSlug && (category ? blog.category === category : true)
    );
    if (filtered.length < limit) {
        const fallbacks = blogsData.filter((blog) => blog.slug !== currentSlug);
        return Array.from(new Set([...filtered, ...fallbacks])).slice(0, limit);
    }
    return filtered.slice(0, limit);
}
